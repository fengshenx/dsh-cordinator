/**
 * 造一个产品图标元素。
 *
 * @param {string} glyph - 字形名，如 `folder-close`
 * @param {object} [options] - 选项
 * @param {number} [options.size] - 边长，默认取字形自带值
 * @returns {object} React 元素
 */
export function productIcon(glyph, options = {}) {
  const artwork = GLYPHS[glyph]
  if (artwork === undefined) throw new Error(`未知图标字形：${glyph}`)
  const size = options.size ?? artwork.size
  return createElement(
    'svg',
    {
      width: size,
      height: size,
      viewBox: '0 0 16 16',
      fill: 'none',
      'aria-hidden': 'true',
      focusable: 'false',
      style: { flex: 'none', display: 'block' },
    },
    ...artwork.paths.map((path) => createElement('path', {
      key: path.d,
      d: path.d,
      fill: path.fill === true ? 'currentColor' : 'none',
      stroke: path.fill === true ? 'none' : 'currentColor',
      strokeWidth: STROKE_WIDTH,
      strokeLinecap: 'round',
      strokeLinejoin: 'round',
      opacity: path.opacity,
    })),
  )
}
